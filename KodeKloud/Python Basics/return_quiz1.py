def square(i): # define a function 'square' that takes one parameter 'i'
    j = i * i # calculate the square of 'i' and store it in 'j'
    return j # return the value of 'j'

num = 2 # assign the value 2 to the variable 'num'
result = square(num) # call the function 'square' with 'num' as the argument
print("THe result of ", num, ' is ', result) # print the result
