testdict = {  # Creating a dictionary
    "brand": "Samsung", # Key: brand, Value: Samsung
    "ram": "3", # Key: ram, Value: 3
    "Os": "Android", # Key: Os, Value: Android
    "year": "2020" # Key: year, Value: 2020
} # End of dictionary

print(testdict.keys()) # Output: dict_keys(['brand', 'ram', 'Os', 'year'])
print(testdict.values()) # Output: dict_values(['Samsung', '3', 'Android', '2020'])
print(testdict.items()) # Output: dict_items([('brand', 'Samsung'), ('ram', '3'), ('Os', 'Android'), ('year', '2020')])
